#!/usr/bin/env python3
"""Generate the Scene colours for the page from the brand tokens.

    python3 scripts/design/gen_scene_tokens.py                 # regenerate from design/tokens.json
    python3 scripts/design/gen_scene_tokens.py path/tokens.json  # refresh design/tokens.json from a copy, then regenerate
    python3 scripts/design/gen_scene_tokens.py --check         # exit 1 if the generated files are stale

`design/tokens.json` is the iPhone's file, copied unchanged from Catchlight-iOS
(`design/tokens.json`), whose `scripts/design/gen_scene_tokens.py` writes the iPhone's
palettes from it. One file, so both apps carry the same colours: refresh it here by passing
the iPhone's copy. This writes:

- `ui/scenes.css`: one custom property per app colour role (`--ground`, `--accent-text`...)
  for every Scene and appearance. `<html data-scene="jade" data-mode="light">` picks one;
  with no `data-scene` the default Scene applies, and with no `data-mode` its Dark.
- `ui/scenes.js`: the Scenes in picker order, with their names and the default.

The roles are the iPhone's (the site and icon roles in the JSON are not used by the app),
except `iconBg` and `iconDot`, which the Scene picker shows. Standard library only. Never
hand-edit the output: change the JSON and run this again.
"""
import json, os, re, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, 'design', 'tokens.json')
CSS = os.path.join(ROOT, 'ui', 'scenes.css')
JS = os.path.join(ROOT, 'ui', 'scenes.js')
ROLES = ['ground', 'surface', 'card', 'raised', 'important', 'importantEdge', 'line', 'outline', 'text', 'muted', 'faint',
         'accent', 'accentText', 'onAccent', 'lit', 'unlit',
         'field', 'onField', 'fieldMuted', 'iconBg', 'iconRing', 'iconDot']
HEX = re.compile(r'^#[0-9A-Fa-f]{6}$')
IDENT = re.compile(r'^[a-z][A-Za-z0-9]*$')


def fail(message):
    sys.exit('gen_scene_tokens: ' + message)


def load(path):
    with open(path, encoding='utf-8') as f:
        data = json.load(f)
    scenes = data.get('scenes') or fail('no "scenes" in ' + path)
    default = data.get('default')
    if default not in scenes:
        fail('default %r is not a Scene' % default)
    for sid, scene in scenes.items():
        if not IDENT.match(sid):
            fail('Scene id %r is not an identifier' % sid)
        if not isinstance(scene.get('name'), str) or not scene['name']:
            fail('%s has no name' % sid)
        for appearance in ('dark', 'light'):
            palette = scene.get(appearance) or fail('%s has no %s palette' % (sid, appearance))
            for role in ROLES:
                value = palette.get(role)
                if not isinstance(value, str) or not HEX.match(value):
                    fail('%s %s %s is %r, not #RRGGBB' % (sid, appearance, role, value))
    return default, scenes


def prop(role):
    return '--' + re.sub(r'([A-Z])', lambda m: '-' + m.group(1).lower(), role)


def block(selector, palette):
    body = ' '.join('%s: %s;' % (prop(role), palette[role].upper()) for role in ROLES)
    return '%s { %s }' % (selector, body)


def render_css(default, scenes):
    out = ['/* GENERATED by scripts/design/gen_scene_tokens.py from design/tokens.json.',
           '   Do not edit by hand: change the JSON and run the script again.',
           '   <html data-scene="..." data-mode="dark|light">: no data-scene is %s, no data-mode is Dark. */' % scenes[default]['name'],
           block(':root', scenes[default]['dark']),
           block(':root[data-mode="light"]', scenes[default]['light'])]
    for sid, scene in scenes.items():
        out.append(block(':root[data-scene="%s"]:not([data-mode="light"])' % sid, scene['dark']))
        out.append(block(':root[data-scene="%s"][data-mode="light"]' % sid, scene['light']))
    return '\n'.join(out) + '\n'


def render_js(default, scenes):
    listed = [{'id': sid, 'name': scene['name'],
               'iconBg': scene['dark']['iconBg'].upper(), 'iconDot': scene['dark']['iconDot'].upper()}
              for sid, scene in scenes.items()]
    return ('// GENERATED by scripts/design/gen_scene_tokens.py from design/tokens.json.\n'
            '// Do not edit by hand: change the JSON and run the script again.\n'
            '// The colour Scenes in picker order. Names are product names: every language keeps the English.\n'
            'const SCENES = %s;\n'
            'const DEFAULT_SCENE = %s;\n') % (json.dumps(listed, indent=2), json.dumps(default))


def main(argv):
    check = '--check' in argv
    paths = [a for a in argv if a != '--check']
    if len(paths) > 1:
        fail('usage: gen_scene_tokens.py [--check] [tokens.json]')
    if paths and check:
        fail('--check reads design/tokens.json only')
    if paths and os.path.abspath(paths[0]) != SOURCE:
        load(paths[0])  # refuse a broken copy before it replaces the vendored one
        shutil.copyfile(paths[0], SOURCE)
    tokens = load(SOURCE)
    outputs = [(CSS, render_css(*tokens)), (JS, render_js(*tokens))]
    stale = 0
    for path, text in outputs:
        name = os.path.relpath(path, ROOT)
        if check:
            try:
                with open(path, encoding='utf-8') as f:
                    current = f.read()
            except FileNotFoundError:
                current = None
            if current != text:
                print('stale: %s does not match design/tokens.json; run scripts/design/gen_scene_tokens.py' % name)
                stale += 1
            else:
                print('current: %s' % name)
        else:
            with open(path, 'w', encoding='utf-8') as f:
                f.write(text)
            print('wrote %s' % name)
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
